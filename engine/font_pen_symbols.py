ALIASES = dict(zip('ΑΒΕΖΗΙΚΜΝΟΡΤΥΧικνο', 'ABEZHIKMNOPTYXikvo'))
ALIASES.update({'ι':'ι','µ':'μ','ν':'v','ϕ':'φ','ϑ':'θ','ϖ':'π','≃':'≈'})


class RoutePen(BasePen):
    def __init__(self):
        super().__init__(None)
        self.routes = []

    def _moveTo(self, point):
        self.routes.append([point])

    def _lineTo(self, point):
        self.routes[-1].append(point)

    def _curveToOne(self, a,b,c):
        p=self.routes[-1][-1]
        for i in range(1,25):
            t=i/24
            u=1-t
            self._lineTo(tuple(u**3*w+3*u*u*t*x+3*u*t*t*y+t**3*z for w,x,y,z in zip(p,a,b,c)))

    def _qCurveToOne(self, a,b):
        p=self.routes[-1][-1]
        for i in range(1,25):
            t=i/24
            u=1-t
            self._lineTo(tuple(u*u*x+2*u*t*y+t*t*z for x,y,z in zip(p,a,b)))

    def _endPath(self):
        pass


def authored_routes(char):
    char=ALIASES.get(char,char)
    if char in EXTRA:
        d=EXTRA[char]
    elif char in GLYPHS:
        _,d=GLYPHS[char]
    else:
        raise ValueError(f'No ordered pen route for {char!r}')
    pen=RoutePen()
    parse_path(d,pen)
    return pen.routes
